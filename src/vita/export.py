"""Export of paper assets: LaTeX macros, tables and CSV data for pgfplots.

Every number printed in the paper is written here from cached results.  Numbers are formatted
with explicit rounding rules; ``check_numbers.py`` recomputes all macros and compares them.
"""
from __future__ import annotations

import re

import numpy as np

from .costs import DESIGN_LABELS, DESIGN_NAMES
from .utils import PAPER

GEN = PAPER / "generated"
DAT = PAPER / "data"


def macro_name_ok(name: str) -> bool:
    return re.fullmatch(r"[A-Za-z]+", name) is not None


def fmt(v, nd=2):
    if isinstance(v, str):
        return v
    if v is None or (isinstance(v, float) and not np.isfinite(v)):
        return "n/a"
    if isinstance(v, (int, np.integer)):
        return f"{int(v)}"
    return f"{v:.{nd}f}"


def numword(n: int) -> str:
    words = {0: "Zero", 1: "One", 2: "Two", 3: "Three", 4: "Four", 5: "Five", 6: "Six", 7: "Seven", 8: "Eight",
             9: "Nine", 10: "Ten", 12: "Twelve", 16: "Sixteen", 24: "TwentyFour"}
    return words[n]


class Numbers:
    """Collects macros; values are stored as already formatted strings."""

    def __init__(self):
        self.m = {}

    def add(self, name, value, nd=2):
        assert macro_name_ok(name), name
        assert name not in self.m, f"duplicate macro {name}"
        self.m[name] = fmt(value, nd)

    def write(self, path=None):
        path = path or GEN / "numbers.tex"
        path.parent.mkdir(parents=True, exist_ok=True)
        lines = ["% generated by vita.export: do not edit"]
        for k in sorted(self.m):
            lines.append(f"\\newcommand{{\\{k}}}{{{self.m[k]}}}")
        path.write_text("\n".join(lines) + "\n")


def write_params_table(cfg, par, path=None):
    """Table II: techno-economic parameters (technology-data) and case-study assumptions."""
    t = par.table
    rows = []
    eff = {"P_pv": "n/a", "P_wd": "n/a", "E_bat": "n/a", "P_bat": f"{par.eta_inv:.2f}",
           "P_ely": f"{par.eta_ely:.3f}/{par.eta_ely_th:.3f}", "E_h2": "n/a",
           "Q_L": f"COP {par.cop_L_nom:.2f}", "Q_H": f"COP {par.cop_H:.2f}", "Q_eb": f"{par.eta_eb:.2f}",
           "Q_gb": f"{par.eta_gb:.2f}", "E_tes": "1.00"}
    unit = {"P_pv": "MW", "P_wd": "MW", "E_bat": "MWh", "P_bat": "MW", "P_ely": "MW$_{\\mathrm{e}}$", "E_h2": "MWh",
            "Q_L": "MW$_{\\mathrm{th}}$", "Q_H": "MW$_{\\mathrm{th}}$", "Q_eb": "MW$_{\\mathrm{th}}$",
            "Q_gb": "MW$_{\\mathrm{th}}$", "E_tes": "MWh"}
    for n, lab in zip(DESIGN_NAMES, DESIGN_LABELS):
        r = t[n]
        rows.append(f"{lab} & {r['capex_eur2020']/1000:.1f} & {r['fom']:.2f} & {int(r['lifetime'])} & "
                    f"{r['annualized']/1000:.2f} & {eff[n]} \\\\")
    lines = [
        "\\begin{table}[!t]",
        "\\centering",
        "\\caption{Techno-Economic Parameters (Technology-Data v0.13.0, Year 2030, EUR of 2020) and Case-Study Assumptions\\label{tab:params}}",
        "\\footnotesize",
        "\\setlength{\\tabcolsep}{2.5pt}",
        "\\begin{tabular}{@{}lccccl@{}}",
        "\\toprule",
        "Technology & Capex & FOM & Life & $\\kappa_i$ & Efficiency \\\\",
        " & [kEUR/u] & [\\%/a] & [a] & [kEUR/(u$\\cdot$a)] & \\\\",
        "\\midrule",
    ] + rows + [
        "\\midrule",
        "\\multicolumn{6}{@{}p{0.98\\columnwidth}@{}}{\\raggedright u: capacity unit (MW, or MWh for storage energy); electrolyzer efficiency: hydrogen/recovered heat. Variable costs [EUR/MWh]: wind %.2f, LT heat pump %.2f, "
        "HT heat pump %.2f, electric boiler %.2f, gas boiler %.2f. Gas %.2f EUR/MWh$_{\\mathrm{th}}$ with %.3f "
        "t/MWh$_{\\mathrm{th}}$; thermal tank energy-to-power ratio %.2f h (technology-data).} \\\\"
        % (par.vom_wd, par.vom_L, par.vom_H, par.vom_eb, par.vom_gb, par.c_gas, par.eps_gas, par.tes_ratio),
        "\\multicolumn{6}{@{}p{0.98\\columnwidth}@{}}{\\raggedright Assumptions: discount rate %.0f\\,\\%%; inflation "
        "%.0f\\,\\%%/a; grid limit %.0f MW; import adder %.0f and export discount %.0f EUR/MWh; unserved energy %.0f "
        "EUR/MWh; PV and wind potential %.0f MW each; thermal tank time constant %.0f d; H$_2$ demand %.0f MW; "
        "CO$_2$ price 80, 150 (central) and 250 EUR/t.} \\\\"
        % (100 * cfg["economics"]["discount_rate"], 100 * cfg["economics"]["inflation"], par.grid, par.imp_add,
           par.exp_sub, par.c_u, cfg["case"]["pv_max"], cfg["case"]["tes_time_constant_days"], par.d_h2),
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
    ]
    path = path or GEN / "tab_params.tex"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")


def write_csv(name, header, rows):
    DAT.mkdir(parents=True, exist_ok=True)
    with open(DAT / name, "w") as f:
        f.write(",".join(header) + "\n")
        for r in rows:
            f.write(",".join(v if isinstance(v, str) else ("nan" if not np.isfinite(v) else fmt(v, 6)) for v in r) + "\n")
